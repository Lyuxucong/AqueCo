
library(aqueco)
otu <- read.csv("otutab.csv",row.names=1,check.names=FALSE)
tax <- read.csv("taxonomy.csv",row.names=1,check.names=FALSE)
md <- read.csv("metadata.csv",row.names=1,check.names=FALSE)
env <- read.csv("env.csv",row.names=1,check.names=FALSE)
tree <- ape::read.tree("otus.tree")
dat <- aq_import(otu,taxonomy=tax,metadata=md,env=env,tree=tree)
null <- aq_null(dat,filter_thres=0.0005,group="Group",seed=123)
nri <- aq_beta_nri(null,runs=500)
nti <- aq_beta_nti(null,runs=500)
rc <- aq_rcbray(null,runs=1000)
assembly <- aq_assembly(nti,rc,group="Group",comparison="within")
print(assembly$summary)
p1 <- aq_null_plot(nti,threshold=c(-2,2))
p2 <- aq_assembly_plot(assembly)
p3 <- aq_null_plot(nti,type="heatmap",cluster=TRUE)
print(p1); print(p2); print(p3)
aq_null_export(nri,"AqueCo")
aq_null_export(nti,"AqueCo")
aq_null_export(rc,"AqueCo")
aq_null_export(assembly,"AqueCo")
